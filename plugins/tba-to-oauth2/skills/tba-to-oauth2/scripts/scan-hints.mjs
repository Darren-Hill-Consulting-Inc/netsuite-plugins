#!/usr/bin/env node
// Usage: node scan-hints.mjs <root> [--max-per-file <n>]
// First-pass locator for NetSuite authentication in a repo. Prints {hits, skipped} as JSON.
// A hit is a location only (file, line, patternId, kind), never the matched text, so secrets in
// the scanned repo never reach the output. Claude confirms every hit by reading the code against
// references/detection-patterns.md; this script only says where to look.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { runIfMain } from './lib/cli.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));

export const PATTERNS = JSON.parse(fs.readFileSync(path.join(HERE, 'scan-patterns.json'), 'utf8'))
  .map((p) => ({ ...p, re: new RegExp(p.regex, p.flags) }));

// Directory name -> skip reason. `.git` is skipped silently: it never holds the repo's code.
const SKIP_DIRS = new Map([
  ['node_modules', 'vendored'],
  ['bower_components', 'vendored'],
  ['vendor', 'vendored'],
  ['.venv', 'vendored'],
  ['venv', 'vendored'],
  ['site-packages', 'vendored'],
  ['dist', 'build-output'],
  ['build', 'build-output'],
  ['target', 'build-output'],
  ['__pycache__', 'build-output'],
]);
const SILENT_DIRS = new Set(['.git']);

const MAX_BYTES = 1024 * 1024;
const GENERATED_MARKER = /<auto-generated|@generated|\bGenerated by\b|DO NOT EDIT/;
const GENERATED_HEAD_LINES = 5;
// Config files hold credentials and often carry "managed by…, do not edit" headers: always scan them.
const CONFIG_EXT = new Set(['.env', '.yml', '.yaml', '.json', '.ini', '.properties', '.toml', '.cfg']);
const isConfig = (name) => name === '.env' || name.startsWith('.env.') || CONFIG_EXT.has(path.extname(name).toLowerCase());

const isBinary = (buf) => buf.subarray(0, 8000).includes(0);
const isGenerated = (lines) => lines.slice(0, GENERATED_HEAD_LINES).some((l) => GENERATED_MARKER.test(l));

/**
 * @param {string} root directory to scan
 * @param {{maxPerFile?: number}} [opts] most lines with hits reported per file; a capped file is
 *   listed in `skipped` with reason `hit-cap` so it gets read in full
 * @returns {{hits: {file: string, line: number, patternId: string, kind: string}[], skipped: {path: string, reason: string}[]}}
 */
export function scanHints(root, { maxPerFile = 20 } = {}) {
  const base = path.resolve(root);
  const hits = [];
  const skipped = [];
  const rel = (abs) => path.relative(base, abs).split(path.sep).join('/');

  function scanFile(abs) {
    const file = rel(abs);
    let buf;
    try {
      if (fs.statSync(abs).size > MAX_BYTES) return skipped.push({ path: file, reason: 'too-large' });
      buf = fs.readFileSync(abs);
    } catch {
      return skipped.push({ path: file, reason: 'unreadable' });
    }
    if (isBinary(buf)) return skipped.push({ path: file, reason: 'binary' });
    const lines = buf.toString('utf8').split(/\r\n|\r|\n/);
    if (!isConfig(path.basename(abs)) && isGenerated(lines)) return skipped.push({ path: file, reason: 'generated' });

    let reported = 0;
    for (let i = 0; i < lines.length; i++) {
      const matched = PATTERNS.filter((p) => p.re.test(lines[i]));
      if (!matched.length) continue;
      if (reported === maxPerFile) return skipped.push({ path: file, reason: 'hit-cap' });
      reported++;
      for (const p of matched) hits.push({ file, line: i + 1, patternId: p.id, kind: p.kind });
    }
  }

  function walk(dir) {
    let entries;
    try {
      entries = fs.readdirSync(dir, { withFileTypes: true });
    } catch {
      return skipped.push({ path: rel(dir) || '.', reason: 'unreadable' });
    }
    entries = entries.sort((a, b) => (a.name < b.name ? -1 : 1));
    for (const e of entries) {
      const abs = path.join(dir, e.name);
      if (e.isDirectory()) {
        if (SILENT_DIRS.has(e.name)) continue;
        if (SKIP_DIRS.has(e.name)) skipped.push({ path: rel(abs), reason: SKIP_DIRS.get(e.name) });
        else walk(abs);
      } else if (e.isFile()) {
        scanFile(abs);
      }
      // Symlinks are neither: not followed, so a link loop can't hang the walk.
    }
  }

  walk(base);
  return { hits, skipped };
}

export async function run({ argv = process.argv.slice(2), stdout = process.stdout, stderr = process.stderr } = {}) {
  const usage = 'usage: node scan-hints.mjs <root> [--max-per-file <n>]\n';
  const args = [...argv];
  let maxPerFile = 20;
  const capAt = args.indexOf('--max-per-file');
  if (capAt !== -1) maxPerFile = Number(args.splice(capAt, 2)[1]);
  const [root, ...extra] = args;
  if (!root || extra.length || !Number.isInteger(maxPerFile) || maxPerFile < 1) {
    stderr.write(usage);
    return 2;
  }
  if (!fs.existsSync(root) || !fs.statSync(root).isDirectory()) {
    stderr.write(`not a directory: ${root}\n${usage}`);
    return 2;
  }
  stdout.write(JSON.stringify(scanHints(root, { maxPerFile }), null, 2) + '\n');
  return 0;
}

runIfMain(import.meta.url, run);
